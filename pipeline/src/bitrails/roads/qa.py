"""data/roads/reports/qa.md: the rows a human has to settle before the island total is trustworthy.

Three lists, each actionable through data/roads/roads_overrides.yaml:
  ownership disagreements   WSDOT's public-road inventory vs the City's street layer
  name mismatches           kind `different` first: usually the geometric match grabbed the
                            neighbouring street's attributes
  unknown ownership         no agency centerline matched and the street's own segments do not
                            agree, so these metres are NOT in the island total
"""
from __future__ import annotations

from .classify import RoadRule, RoadSegment, is_included
from .group import Road

MI = 1609.344
TOP = 40


def _table(headers: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"] + \
           ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def qa_report_text(segments: list[RoadSegment], roads: list[Road],
                   disagreements: list[tuple[str, str, str]],
                   mismatches: list[tuple[str, str, str, str]], rule: RoadRule) -> str:
    by_id = {s.id: s for s in segments}
    unknown = sorted((s for s in segments if s.ownership == "unknown"), key=lambda s: -s.length_m)
    unknown_m = sum(s.length_m for s in unknown)
    counted_m = sum(s.length_m for s in segments if is_included(s, rule))
    out = ["# Road data QA", "",
           "Generated by `bitroads build`. Fix a row by recording the verdict in "
           "`data/roads/roads_overrides.yaml` (never by editing generated data).", "",
           "| open question | rows | metres |", "|---|---|---|",
           f"| ownership disagreements (WSDOT vs City) | {len(disagreements)} | "
           f"{sum(by_id[i].length_m for i, *_ in disagreements if i in by_id):.0f} |",
           f"| name mismatches (all kinds) | {len(mismatches)} | "
           f"{sum(by_id[i].length_m for i, *_ in mismatches if i in by_id):.0f} |",
           f"| unknown ownership (uncounted) | {len(unknown)} | {unknown_m:.0f} |", "",
           f"Unknown ownership is {unknown_m / 1000:.1f} km / {unknown_m / MI:.1f} mi held out of the "
           f"{counted_m / 1000:.1f} km / {counted_m / MI:.1f} mi island total: settling it can only move "
           "the goal up.", "",
           "## Ownership disagreements", "",
           "WSDOT's Local Agency Public Road inventory and the City's rd_Streets layer disagree about "
           "the same centerline. The build takes WSDOT; override where local knowledge says otherwise.", ""]
    rows = []
    for sid, wsdot, city in sorted(disagreements, key=lambda d: -(by_id[d[0]].length_m if d[0] in by_id else 0)):
        s = by_id.get(sid)
        if s is None:
            continue
        rows.append([f"`{sid}`", s.name or "(unnamed)", f"{s.length_m:.0f}", wsdot, city, s.category])
    out += _table(["segment", "name", "m", "WSDOT", "City", "category"], rows[:TOP]) if rows else ["(none)"]
    if len(rows) > TOP:
        out += ["", f"... and {len(rows) - TOP} more."]
    out += ["", "## Name mismatches", "",
            "`different` = the sources name this centerline two unrelated things, which usually means the "
            "10 m match buffer picked up the street next door, and the attributes (including ownership) "
            "came with it. `type` = same words, different street type. `spelling` = one token apart.", ""]
    order = {"different": 0, "spelling": 1, "type": 2}
    rows = []
    for sid, osm, agency, kind in sorted(mismatches, key=lambda m: (order.get(m[3], 9),
                                                                   -(by_id[m[0]].length_m if m[0] in by_id else 0))):
        s = by_id.get(sid)
        if s is None:
            continue
        rows.append([kind, f"`{sid}`", osm, agency, f"{s.length_m:.0f}", s.ownership, s.ownership_source])
    out += _table(["kind", "segment", "OSM name", "agency name", "m", "ownership", "ownership from"],
                  rows[:TOP]) if rows else ["(none)"]
    if len(rows) > TOP:
        out += ["", f"... and {len(rows) - TOP} more (full list in "
                    "`data/roads/canonical/segments.geojson`: compare `name` with `agency_names`)."]
    out += ["", "## Unknown ownership (not counted)", "",
            "No agency centerline matched these, and the other segments of the same street do not agree "
            "well enough to inherit from (see `infer_unknown_ownership`). Most are private plat roads; "
            "each one confirmed public adds its metres to the goal.", ""]
    rows = [[f"`{s.id}`", s.name or "(unnamed)", f"{s.length_m:.0f}", s.category,
             ", ".join(s.sources)] for s in unknown[:TOP]]
    out += _table(["segment", "name", "m", "category", "sources"], rows) if rows else ["(none)"]
    if len(unknown) > TOP:
        out += ["", f"... and {len(unknown) - TOP} more."]
    named = sorted({s.name for s in unknown if s.name})
    out += ["", f"Distinct street names with unknown ownership: {len(named)}.", ""]
    return "\n".join(out) + "\n"
