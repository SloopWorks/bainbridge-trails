"""`bitroads dist` also writes data/roads/reports/summary.md: the human read-out of the roads dataset."""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from .build import DEFAULT_CANONICAL, DEFAULT_REPORT, DEFAULT_RULE, DEFAULT_SOURCES, ROADS

MI = 1609.344


def _km(m: float) -> str:
    return f"{m / 1000:.1f} / {m / MI:.1f}"


def _table(headers: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"] + \
           ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def build_summary(canonical: Path = DEFAULT_CANONICAL, sources_path: Path = DEFAULT_SOURCES,
                  rule_path: Path = DEFAULT_RULE, dist_roads: list[dict] | None = None) -> str:
    doc = json.loads((Path(canonical) / "roads.json").read_text())
    ds = doc["dataset"]
    rule = doc["rule"]
    out = ["# Road data summary", "",
           "Generated by `bitroads dist`. Rebuild: `bitroads build && bitroads dist`. "
           "Lengths: km / miles.", "", "## The goal", "",
           f"**Counted road network: {_km(doc['island_total_m'])}** "
           f"({ds['segments_included']} of {ds['segments']} segments, {ds['roads_counted']} of "
           f"{ds['roads']} named roads).", "",
           f"Shippable share (OSM geometry the app can draw): {_km(doc['island_total_shippable_m'])}.", "",
           "Counted = " + ", ".join(rule["categories"]) + " owned by " +
           ", ".join(o.replace("public_", "") for o in rule["ownerships"]) +
           "; private roads, named lanes and driveways are mapped but not counted.", "",
           "## Everything mapped", "",
           f"| metric | value |", "|---|---|",
           f"| segments (all) | {ds['segments']} |",
           f"| segments with shippable geometry | {ds['segments_shippable']} |",
           f"| segments counted by rule | {ds['segments_included']} |",
           f"| named roads | {ds['roads']} ({ds['roads_counted']} counted) |",
           f"| all mapped centerline | {_km(ds['length_m'])} |",
           f"| counted (the goal) | {_km(doc['island_total_m'])} |",
           f"| counted + shippable geometry | {_km(doc['island_total_shippable_m'])} |", "",
           "## Per category", ""]
    out += _table(["category", "segments", "km / mi", "counted km / mi", "shippable km / mi"],
                  [[c, s["segments"], _km(s["m"]), _km(s["included_m"]), _km(s["shippable_m"])]
                   for c, s in ds["categories"].items() if s["segments"]])
    out += ["", "## Per ownership", ""]
    out += _table(["ownership", "segments", "km / mi", "counted km / mi"],
                  [[o, s["segments"], _km(s["m"]), _km(s["included_m"])]
                   for o, s in ds["ownerships"].items() if s["segments"]])
    out += ["", "## Data quality", "", "| check | count |", "|---|---|"]
    qa = doc.get("qa") or {}
    out += [f"| {k} | {v} |" for k, v in sorted(qa.items()) if not isinstance(v, dict)]
    for k, v in sorted(qa.items()):
        if isinstance(v, dict):
            out += [f"| {k}: {kk} | {vv} |" for kk, vv in sorted(v.items())]
    out += ["", "`ownership_disagreements` = centerlines where WSDOT's public-road inventory and the "
            "City's street layer disagree public vs private; the build takes WSDOT and lists the rest "
            "here. `name_mismatches` = OSM and the agency name the same centerline differently after "
            "abbreviation and direction are normalised away.", ""]
    if dist_roads:
        longest = sorted(dist_roads, key=lambda r: -(r.get("computed_length_mi") or 0))[:15]
        out += ["## Longest roads (shippable miles)", ""]
        out += _table(["road", "mi", "category", "ownership", "climb m", "counted"],
                      [[r["name"], r["computed_length_mi"], r["category"], r["ownership"],
                        r.get("climb_total_m"), "yes" if r.get("counted") else "no"] for r in longest])
        gap = [r for r in dist_roads if (r.get("agency_only_length_mi") or 0) > 0.05]
        out += ["", f"Roads whose agency mileage exceeds what ships: {len(gap)}", ""]
    srcs = yaml.safe_load(Path(sources_path).read_text())["sources"]
    out += ["## Sources", "", ]
    out += _table(["id", "kind", "rank", "redistribution"],
                  [[s["id"], s["kind"], s.get("geometry_rank") or "", s["redistribution"]] for s in srcs])
    out += ["", f"Inclusion rule: `{rule_path.name}` -> {json.dumps(rule, sort_keys=True)}", ""]
    return "\n".join(out) + "\n"


def write_summary(canonical: Path = DEFAULT_CANONICAL, out: Path = ROADS / "reports" / "summary.md",
                  sources_path: Path = DEFAULT_SOURCES, rule_path: Path = DEFAULT_RULE,
                  dist_roads: list[dict] | None = None) -> Path:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_summary(canonical, sources_path, rule_path, dist_roads))
    return out
