"""`data/reports/summary.md`: owner-facing data report (deterministic; aggregates + names only, no geometry)."""
from __future__ import annotations

import json
import re
from collections import defaultdict
from difflib import SequenceMatcher
from pathlib import Path

import yaml

from .boundary import REPO_ROOT
from .trails import map_key

DATA = REPO_ROOT / "data"
MI, SHORT_M = 1609.344, 80.0


def _km(m: float) -> str:
    return f"{m / 1000:.1f}"


def conflict_counts(conflicts_md: Path) -> list[tuple[str, int]]:
    rows = re.findall(r"^\| (\w+) \| (\d+) \|$", conflicts_md.read_text(), re.M)
    return [(k, int(n)) for k, n in rows if k != "kind"]


def short_trails(trails: list[dict], limit_m: float = SHORT_M) -> list[dict]:
    return sorted((t for t in trails if t["computed_length_mi"] * MI < limit_m), key=lambda t: t["id"])


def near_duplicates(trails: list[dict], ratio: float = 0.88) -> list[tuple[str, str]]:
    """Name pairs that normalize equal, where one is a word-prefix of the other, or are very similar."""
    keys = sorted(((map_key(t["name"]), t["name"]) for t in trails), key=lambda x: x[1])
    out = []
    for i, (ka, na) in enumerate(keys):
        for kb, nb in keys[i + 1:]:
            if not ka or not kb or na == nb:
                continue
            wa, wb = ka.split(), kb.split()
            short, long_ = (wa, wb) if len(wa) <= len(wb) else (wb, wa)
            if long_[:len(short)] == short or SequenceMatcher(None, ka, kb).ratio() >= ratio:
                out.append((na, nb))
    return sorted(set(out))


def _table(headers: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    return out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def agency_only_rows(private: Path, trails: list[dict]) -> list[list]:
    """[trail/group, category, segments, km, counted km] for non-redistributable geometry, largest first."""
    if not private.exists():
        return []
    name_of = {t["id"]: t["name"] for t in trails}
    acc: dict[tuple[str, str], list] = defaultdict(lambda: [0, 0.0, 0.0])
    for f in json.loads(private.read_text())["features"]:
        p = f["properties"]
        label = name_of.get((p.get("trail_ids") or [None])[0]) or p.get("name") or "(unnamed)"
        a = acc[(label, p["category"])]
        a[0] += 1
        a[1] += p["length_m"]
        a[2] += p["length_m"] if p["included"] else 0
    rows = sorted(acc.items(), key=lambda kv: (-kv[1][1], kv[0]))
    return [[n, c, v[0], _km(v[1]), _km(v[2])] for (n, c), v in rows]


def manager_stats(features: list[dict], private: Path) -> dict[str, list]:
    acc: dict[str, list] = defaultdict(lambda: [0, 0.0, 0.0])
    feats = list(features)
    if private.exists():
        feats += json.loads(private.read_text())["features"]
    for f in feats:
        p = f["properties"]
        a = acc[p.get("manager") or "(none)"]
        a[0] += 1
        a[1] += p["length_m"]
        a[2] += p["length_m"] if p["included"] else 0
    return acc


OFFICIAL_GAP = 0.15


def official_vs_computed_rows(trails: list[dict]) -> list[list]:
    """Rows for trails with an official length. Each trail dict: name, official_length_mi, official_length_source,
    computed_mi (shippable), agency_only_mi. diff_% = (computed + agency_only - official) / official;
    flagged with a warning sign when |diff| exceeds OFFICIAL_GAP."""
    rows = []
    for t in sorted(trails, key=lambda t: t["name"]):
        off = t.get("official_length_mi")
        if off is None:
            continue
        diff = (t["computed_mi"] + t["agency_only_mi"] - off) / off
        flag = " ⚠" if abs(diff) > OFFICIAL_GAP else ""
        rows.append([t["name"], off, round(t["computed_mi"], 3), round(t["agency_only_mi"], 3),
                     f"{diff * 100:+.0f}%{flag}", t.get("official_length_source") or ""])
    return rows


def build_summary(canonical: Path, conflicts_md: Path, sources_path: Path, inclusion_path: Path) -> str:
    doc = json.loads((canonical / "trails.json").read_text())
    ds, trails = doc["dataset"], doc["trails"]
    feats = json.loads((canonical / "segments.geojson").read_text())["features"]
    private = canonical / "private" / "agency_only.geojson"
    L = ["# Data summary", "",
         "Generated by `bitrails dist`. Rebuild: `bitrails build && bitrails dist`. Lengths: km / miles.", "",
         "## Totals", ""]
    L += _table(["metric", "value"], [
        ["segments (all)", ds["segments"]], ["segments with shippable geometry", ds["segments_shippable"]],
        ["segments counted by rule", ds["segments_included"]], ["trails", ds["trails"]],
        ["all mapped paths", f"{_km(ds['length_m'])} km / {ds['length_m'] / MI:.1f} mi"],
        ["island total (rule, incl. agency-only)",
         f"{_km(doc['island_total_m'])} km / {doc['island_total_mi']} mi"],
        ["island total shippable (app v1 uses this)",
         f"{_km(doc['island_total_shippable_m'])} km / {doc['island_total_shippable_mi']} mi"]])
    L += ["", "Agency-only = real trail whose geometry is not redistributable (kept private), so the app cannot "
          "draw it yet. The gap between the two totals is that length.", "", "## Per category", ""]
    L += _table(["category", "segments", "km", "counted km", "shippable km"],
                [[c, s["segments"], _km(s["m"]), _km(s["included_m"]), _km(s["shippable_m"])]
                 for c, s in ds["categories"].items()])
    L += ["", "## Per manager", ""]
    mg = manager_stats(feats, private)
    L += _table(["manager", "segments", "km", "counted km"], [[m, v[0], _km(v[1]), _km(v[2])]
                                                              for m, v in sorted(mg.items())])
    L += ["", "## Conflicts", "", "Full detail: [conflicts.md](conflicts.md).", ""]
    L += _table(["kind", "count"], [[k, n] for k, n in conflict_counts(conflicts_md)])
    L += ["", "## Trails: official vs computed miles", ""]
    n_off = sum(t["official_length_mi"] is not None for t in trails)
    L += [f"Official mileage is set on {n_off} of {len(trails)} trails: no source has an agency mileage field "
          "(set it per trail in `trails_overrides.yaml`). Computed = sum of segment lengths. "
          "Gain/loss follow walking order (2 m hysteresis).", ""]
    L += _table(["trail", "manager", "park", "segs", "official mi", "computed mi", "gain m", "loss m"],
                [[t["name"], t["manager"] or "", t["park"] or "", len(t["segment_ids"]),
                  t["official_length_mi"] if t["official_length_mi"] is not None else "", t["computed_length_mi"],
                  t.get("gain_m", ""), t.get("loss_m", "")]
                 for t in sorted(trails, key=lambda t: (-t["computed_length_mi"], t["id"]))])
    ship_len = {f["properties"]["id"]: f["properties"]["length_m"] for f in feats}
    ovc = []
    for t in trails:
        comp = sum(ship_len.get(i, 0.0) for i in t["segment_ids"]) / MI
        ovc.append({**t, "computed_mi": comp, "agency_only_mi": max(0.0, t["computed_length_mi"] - comp)})
    orows = official_vs_computed_rows(ovc)
    L += ["", "## Official vs computed length", "",
          "Official = agency-published mileage set in `trails_overrides.yaml` with a cited source. computed_mi = "
          "shippable segments (what the app can draw); agency_only_mi = private geometry. diff_% compares "
          "computed + agency-only with official; ⚠ = off by more than 15%.", ""]
    L += _table(["trail", "official_mi", "computed_mi", "agency_only_mi", "diff_%", "source"], orows) \
        if orows else ["(no trail has an official length yet)"]
    L += ["", "## Owner review", "",
          "### Classification rule (`data/inclusion.yaml`)", "",
          "A segment counts toward the island total when its public_access is not `no` and its category is in "
          "the list below, or it is a `connector` that belongs to a trail or has a non-road name.", "",
          "```yaml", inclusion_path.read_text().rstrip(), "```", "",
          "Edit the yaml, then re-run `bitrails build && bitrails dist`; no re-collection needed.", ""]
    gaz = [t for t in trails if re.search("gazzam|veterane", t["name"].lower())]
    L += ["### Gazzam merge question", "",
          "Two agency datasets named the same trails differently, so `trails_overrides.yaml` already merges "
          "`Gazzam Main Trail` into `Gazzam Lake Main Trail` (same for Grand Forest East, Blakely to Eagledale, "
          "Fort Ward to Blakely Harbor). Confirm that is right, and say whether the remaining Gazzam trails "
          "below (Loop, Veterane pieces) are distinct trails or belong to the main trail.", ""]
    L += _table(["trail id", "name", "computed mi"], [[t["id"], t["name"], t["computed_length_mi"]] for t in gaz])
    sh = short_trails(trails)
    L += ["", f"### Trails under {int(SHORT_M)} m ({len(sh)})", "",
          "Usually a name carried by a tiny OSM piece (bridge, road-end stub). Drop or merge via overrides.", ""]
    L += _table(["trail", "m", "park"], [[t["name"], round(t["computed_length_mi"] * MI), t["park"] or ""] for t in sh])
    nd = near_duplicates(trails)
    L += ["", f"### Near-duplicate names ({len(nd)} pairs)", ""]
    L += [f"- {a} / {b}" for a, b in nd]
    ao = agency_only_rows(private, trails)
    L += ["", "### Agency-only trails missing from the app until permission", "",
          f"{len(ao)} groups, {sum(float(r[3]) for r in ao):.1f} km total ({sum(float(r[4]) for r in ao):.1f} km "
          "counted in the island total; the rest is `planned` STO alignment or uncounted). Geometry exists privately "
          "but is not redistributable; the app shows none of it until the agency grants permission.", ""]
    L += _table(["trail", "category", "segments", "km", "counted km"], ao) if ao else ["(private geometry not present)"]
    ship_ids = {f["properties"]["id"] for f in feats}
    dropped = [t for t in trails if not any(i in ship_ids for i in t["segment_ids"])]
    L += ["", f"### Trails omitted from the app (no shippable segment): {len(dropped)}", ""]
    L += [f"- {t['name']} ({t['computed_length_mi']} mi)" for t in dropped] or ["(none)"]
    L += ["", "Shipped trails in `data/dist/trails.json` use shippable segments only (length, gain/loss, trailheads); "
          "`agency_only_length_mi` is the part still missing.", ""]
    srcs = yaml.safe_load(sources_path.read_text())["sources"]
    L += ["### Agency data licensing (your call)", "",
          "BIMPRD, City and STO datasets have `redistribution: unknown` in sources.yaml. Shipped geometry comes "
          "from OSM (ODbL) and USGS; agency data contributes names/attributes only and is credited as such in "
          "`data/ATTRIBUTION.md`. Confirm that is acceptable, or ask the agencies for permission (which would "
          "also unlock the agency-only trails above).", ""]
    urls = sorted({(t["park"] or t["name"], t["official_map_url"]) for t in trails if t["official_map_url"]})
    L += ["", "### BIMPRD PDF URLs to verify in a browser", "",
          "Matched to trails by name; none were opened by the pipeline.", ""]
    L += _table(["park / trail", "url"], [[a, b] for a, b in urls])
    pdfs = [s for s in srcs if s["kind"] == "pdf_map" and "BIMPRD" in (s.get("attribution") or "")
            and s.get("endpoint") and s["endpoint"] not in {u for _, u in urls}]
    if pdfs:
        L += ["", "Other BIMPRD PDFs in sources.yaml not linked to any trail:", ""]
        L += [f"- {s['name']}: {s['endpoint']}" for s in pdfs]
    return "\n".join(L) + "\n"


def write_summary(canonical: Path = DATA / "canonical", out: Path = DATA / "reports" / "summary.md",
                  conflicts_md: Path = DATA / "reports" / "conflicts.md", sources_path: Path = DATA / "sources.yaml",
                  inclusion_path: Path = DATA / "inclusion.yaml") -> Path:
    out.write_text(build_summary(canonical, conflicts_md, sources_path, inclusion_path))
    return out
