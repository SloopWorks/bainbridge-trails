package com.bainbridgetrails.play.schedule

import com.bainbridgetrails.play.config.Goal
import kotlinx.datetime.LocalDate
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * plan.md §3 (AC 8): `docs/play/e2e-ids.env` pins the treasure features the e2e replays walk: the first treasure
 * placement of week 2026-10-26 per goal, on a Play-safe feature `scripts/emu-route.sh` / `sim-route.sh` can replay (a
 * trails.json / roads.json id with segments). Regenerate with `-Pplay.updateGolden=true`; skipped without datasets.
 */
class E2eFixtureTest {
    private val env = File(RealPack.ROOT, "docs/play/e2e-ids.env")
    private val week = LocalDate(2026, 10, 26)

    @Test
    fun `e2e-ids env treasure ids are placements of week 2026-10-26`() {
        val index = JvmDatasetPlaceIndex.loadOrSkip("E2eFixtureTest")
        val s = RealPack.scheduler(index)
        val ids = Goal.entries.associateWith { goal ->
            val occ = s.dayPlan(week, goal).occurrences.single { it.itemId == "treasure-weekly-${goal.name}" }
            assertEquals("treasure-weekly-${goal.name}@2026-10-26", occ.key)
            val first = occ.placements.first()
            val id = assertNotNull(first.featureId)
            assertTrue(index.feature(id)?.goal == goal, "$id is a ${goal.name} feature")
            val ref = if (goal == Goal.trails) TrailRef(id) else RoadRef(id)
            assertTrue(index.segments(ref).isNotEmpty(), "$id has segments (emu-route.sh replays them)")
            assertTrue(id in RealPack.derived.getValue(goal).playSafe, "$id is Play-safe")
            first
        }
        val text = buildString {
            append("# Generated by E2eFixtureTest (app/play): the first treasure placement of week 2026-10-26 per goal,\n")
            append("# pack ${s.config.version}. Used by the AC 8 e2e script (docs/play/plan.md §3). Do not edit by hand:\n")
            append("# cd app && ./gradlew :play:jvmTest -Pplay.updateGolden=true\n")
            append("E2E_TREASURE_ROAD=${ids.getValue(Goal.roads).featureId}\n")
            append("E2E_TREASURE_ROAD_KEY=${ids.getValue(Goal.roads).key}\n")
            append("E2E_TREASURE_TRAIL=${ids.getValue(Goal.trails).featureId}\n")
            append("E2E_TREASURE_TRAIL_KEY=${ids.getValue(Goal.trails).key}\n")
        }
        if (RealPack.update) env.writeText(text)
        assertEquals(text, env.readText())
    }

    @Test
    fun `e2e-ids env is well formed`() {
        assertTrue(env.exists(), "${env.path} missing: run with -Pplay.updateGolden=true and the datasets")
        val vars = env.readLines().filter { it.isNotBlank() && !it.startsWith("#") }.associate { it.substringBefore('=') to it.substringAfter('=') }
        assertTrue(vars.getValue("E2E_TREASURE_ROAD").startsWith("road-"))
        assertTrue(vars.getValue("E2E_TREASURE_TRAIL").startsWith("trail-"))
    }
}
